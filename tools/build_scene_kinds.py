"""Sort the scripted sequences that animate Isaac into kinds, for the bots.

A sequence running on the player ([player+0x238], GUID at +0x24) tells by its
action animation what it is: igc_ in-game cinematic, se_ scripted event, pc_ a
short player action, vt_/seh_ a vision or horror moment. The bots hide only in
the kinds the INI asks for ([Bot] HideInCinematics and friends).

    python tools/build_scene_kinds.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "analysis" / "catalog" / "entities.jsonl"
HEADER = ROOT / "src" / "generated_scene_kinds.h"
CLASSES = {"ScriptedSequence", "ScriptedEventSequence"}
KINDS = {"igc": "Cinematic", "se": "Event", "pc": "Action", "vt": "Vision", "seh": "Vision"}


def main():
    rows = {}
    for line in CATALOG.open(encoding="utf-8"):
        if "ScriptedSequence" not in line and "ScriptedEventSequence" not in line:
            continue
        entity = json.loads(line)
        images = entity.get("images") or []
        if not images or images[0].get("class") not in CLASSES:
            continue
        anim = ""
        for image in images:
            for field in image.get("fields", []):
                if field.get("name") == "CMD_SetActionAnimationString":
                    anim = str(field.get("string_candidate") or "").lower()
        match = re.match(r"(igc|seh|se|pc|vt)_", anim)
        # Only what can run on Isaac: a player animation or a player action.
        if not match or ("player" not in anim and match.group(1) != "pc"):
            continue
        kind = KINDS[match.group(1)]
        previous = rows.get(entity["guid"])
        if previous and previous[0] != kind:
            raise ValueError(f"{entity['guid']} is both {previous[0]} and {kind}")
        rows[entity["guid"]] = (kind, anim)
    lines = ["// Generated by tools/build_scene_kinds.py.", "#pragma once", "#include <cstdint>", "",
             "namespace coop_scenes {",
             "enum class Kind : uint8_t { Unknown, Cinematic, Event, Action, Vision };",
             "struct Sequence { uint32_t guid[4]; Kind kind; const char* anim; };",
             "inline constexpr Sequence kSequences[] = {"]
    for guid, (kind, anim) in sorted(rows.items()):
        words = ", ".join(f"0x{w}u" for w in guid.split("-"))
        lines.append(f"    {{{{{words}}}, Kind::{kind}, {json.dumps(anim)}}},")
    lines += ["};", "}  // namespace coop_scenes", ""]
    HEADER.write_text("\n".join(lines), encoding="utf-8")
    counts = {}
    for kind, _ in rows.values():
        counts[kind] = counts.get(kind, 0) + 1
    print(f"{len(rows)} player sequences: {counts}")


if __name__ == "__main__":
    main()
