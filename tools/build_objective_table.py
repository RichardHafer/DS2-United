"""Build src/generated_objective_table.h: what the Objective mode watches on each MP map.

Per map: the round clock's own time (the round TimerUtil's CMD_SetTime) and the
TimerSets that feed that clock (their activation message hash, seconds, and
whether they add or set). Shared by all maps: the five objectives announce
themselves with obj_1_new .. obj_5_new, the humans win with var_op_human_win,
round_end_humanwin or online_end_round_human_win, and the necromorphs with
online_end_round_necro_win or round_end_necrowin.

Sources: analysis/catalog/entities.jsonl (decoded fields) for the five shipped
maps, the baked images (tools/mp_baked.py) for the two Outbreak maps.

usage: python tools/build_objective_table.py
"""
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import mp_baked  # noqa: E402

CATALOG = ROOT / "analysis" / "catalog" / "entities.jsonl"
OUT = ROOT / "src" / "generated_objective_table.h"
# the names the map table (coop_mpmap::kMapTable) and the director use
MAPS = {"mp_bombrun": "mp_bombRun", "mp_detonate": "mp_detonate", "mp_escape": "mp_escape", "mp_gov": "mp_gov", "mp_solar": "mp_solar",
        "pdlc_mp_mall": "pdlc_mp_mall", "pdlc_mp_school": "pdlc_mp_school"}
ROUND_STARTS = {"start_roundtimer", "round_timer_start"}
WIN = ["var_op_human_win", "round_end_humanwin", "online_end_round_human_win"]
LOSS = ["online_end_round_necro_win", "round_end_necrowin"]


def f32(v):
    return struct.unpack("<f", struct.pack("<I", v & 0xFFFFFFFF))[0]


def map_of(archive):
    a = archive.lower()
    return next((MAPS[m] for m in MAPS if m in a), None)


def main():
    names = set(WIN + LOSS + ["obj_%d_new" % i for i in range(1, 6)] + ["obj_%d_complete" % i for i in range(1, 6)] +
                ["mm_obj_%d_complete" % i for i in range(1, 6)])
    rounds = {}       # guid -> (map, seconds)
    sets = []         # (map, name, hash, seconds, relative, ref)
    with open(CATALOG, encoding="utf-8") as f:
        for line in f:
            if '"TimerUtil"' not in line and '"TimerSet"' not in line:
                continue
            e = json.loads(line)
            mp = map_of(e.get("archive", ""))
            if not mp:
                continue
            for im in e["images"]:
                named = {fl["name"]: fl for fl in im.get("fields", [])}
                for fl in im.get("fields", []):
                    if fl.get("string_candidate"):
                        names.add(fl["string_candidate"])
                if im.get("class") == "TimerUtil":
                    start = named.get("CMD_StartTimer", {}).get("string_candidate", "")
                    if start.lower() in ROUND_STARTS:
                        rounds[e["guid"].upper()] = (mp, f32(named.get("CMD_SetTime", {}).get("value", 0)))
                elif im.get("class") == "TimerSet":
                    act = named.get("CMD_Activate", {}).get("string_candidate")
                    if not act:
                        continue
                    sets.append((mp, act, mp_baked.name_hash(act), f32(named.get("CMD_SetTime", {}).get("value", 0)),
                                 bool(named.get("CMD_IncrementTime", {}).get("value")), (named.get("CMD_SetTimerRef", {}).get("guid_candidate") or "").upper()))
    by_hash = {mp_baked.name_hash(n): n for n in names}
    starts = {mp_baked.name_hash(n) for n in ROUND_STARTS}
    for mp, guid, cls, blob in mp_baked.iter_baked({"TimerUtil", "TimerSet"}):
        mp = MAPS[mp]
        if cls == "TimerUtil":
            if struct.unpack_from("<I", blob, 0)[0] in starts:
                rounds[guid] = (mp, struct.unpack_from("<f", blob, 0x54)[0])
        else:
            h = struct.unpack_from("<I", blob, 0)[0]
            sets.append((mp, by_hash.get(h, ""), h, struct.unpack_from("<f", blob, 0x0C)[0], bool(blob[0x10]), mp_baked.guid_at(blob, 0x14)))

    per_map = {mp: {"seconds": 0.0, "bonuses": []} for mp in MAPS.values()}
    for guid, (mp, seconds) in rounds.items():
        per_map[mp]["seconds"] = seconds
    round_guids = set(rounds)
    for mp, name, h, seconds, relative, ref in sets:
        if ref not in round_guids or (relative and seconds <= 0):
            continue
        per_map[mp]["bonuses"].append((h, seconds, relative, name))

    lines = ["// Generated by tools/build_objective_table.py from the entity catalogs - DO NOT EDIT",
             "// The Objective mode's view of each MP map: the round clock's own time and the",
             "// TimerSets that feed it (activation message hash, seconds, adds or sets).",
             "#pragma once", "#include <cstdint>", "", "namespace ds2 {",
             "struct ObjectiveBonus { uint32_t hash; float seconds; bool relative; const char* name; };",
             "struct ObjectiveMap { const char* map; float roundSeconds; const ObjectiveBonus* bonuses; unsigned count; };"]
    for mp, info in per_map.items():
        rows = sorted(info["bonuses"], key=lambda b: b[3])
        lines.append("inline constexpr ObjectiveBonus kObjectiveBonuses_%s[] = {" % mp)
        for h, seconds, relative, name in rows:
            lines.append('    {0x%08Xu, %.1ff, %s, "%s"},' % (h, seconds, "true" if relative else "false", name))
        if not rows:
            lines.append('    {0u, 0.0f, true, ""},')
        lines.append("};")
    lines.append("inline constexpr ObjectiveMap kObjectiveMaps[] = {")
    for mp, info in per_map.items():
        lines.append('    {"%s", %.1ff, kObjectiveBonuses_%s, %d},' % (mp, info["seconds"], mp, len(info["bonuses"])))
    lines.append("};")
    lines.append("// obj_1_new .. obj_5_new: objective n starts (so n - 1 is done)")
    lines.append("inline constexpr uint32_t kObjectiveNew[5] = {%s};" % ", ".join("0x%08Xu" % mp_baked.name_hash("obj_%d_new" % i) for i in range(1, 6)))
    lines.append("// %s" % ", ".join(WIN))
    lines.append("inline constexpr uint32_t kObjectiveWin[] = {%s};" % ", ".join("0x%08Xu" % mp_baked.name_hash(n) for n in WIN))
    lines.append("// %s" % ", ".join(LOSS))
    lines.append("inline constexpr uint32_t kObjectiveLoss[] = {%s};" % ", ".join("0x%08Xu" % mp_baked.name_hash(n) for n in LOSS))
    lines.append("}  // namespace ds2")
    OUT.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    for mp, info in per_map.items():
        print("%-15s round %4.0f s, %d bonus(es): %s" % (mp, info["seconds"], len(info["bonuses"]),
              ", ".join("%s%s%.0f" % (b[3] or "%08X" % b[0], "+" if b[2] else "=", b[1]) for b in info["bonuses"])))
    print("written", OUT)


if __name__ == "__main__":
    main()
