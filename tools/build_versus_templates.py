"""Templates a Versus match spawns at run time out of global_mp_assets.

The MP map gate (runtime_coop_mpmap.inc) blocks global_mp_assets on an MP map,
records included. A Versus round spawns from some of them while it runs: the
necro's cameras, projectiles and aiming data, its death drop list and the
pickups behind it, the vent highlight. Every record the round's roots reach
through GUID fields is listed here (closure over analysis/catalog/entities.jsonl),
except the MP human Player template and its parts (our humans are the campaign
Player) and UI entities, which stay blocked as before.

Writes src/generated_versus_templates.h.
"""
import json
import re
from collections import deque
from pathlib import Path

root = Path(__file__).resolve().parents[1]
ROOTS = [
    "58C9C3B1-0878CD53-3532554C-58583337",  # MPLevelSettings
    "58C9EA2A-CBDF5A07-3532554C-58583337",  # RespawnProxy
    "58CA0CA9-DF9A22B2-3532554C-58583337",  # NecroPlayer pack
    "58CA17A0-B16998A0-3532554C-58583337",  # NecroPlayer lurker
    "58CAC498-725F1CF9-3532554C-58583337",  # NecroPlayer spitter
    "58CB1317-5D04C30B-3532554C-58583337",  # NecroPlayer puker
    "58C9E8A1-BB9C97A1-3532554C-58583337",  # MultiAmmo of the map slashers' drop list 37CA2B52 ([Versus] MpLoot)
]
NOT_FOLLOWED = {"34CA0FEE-ECDB4E92-4F425241-4144454C",  # the MP human Player template
                "38C83B73-97D29540-54544950-32303253"}  # the gun ammo sub-list real MP never spawns
OPEN_GROUPS = {1, 2, 3, 4}  # end_round, round_timer, objective_markers, team_logic: Versus opens them anyway


def main():
    ents = {}
    with (root / "analysis/catalog/entities.jsonl").open(encoding="utf-8") as f:
        for line in f:
            if "global_mp_assets" not in line[:400]:
                continue
            e = json.loads(line)
            if "global_mp_assets" not in e["archive"]:
                continue
            refs = set()
            for img in e["images"]:
                for fl in img["fields"]:
                    if fl.get("guid_candidate"):
                        refs.add(fl["guid_candidate"].upper())
            ents[e["guid"].upper()] = (e["images"][0]["class"], refs)
    block = {}
    text = (root / "src/generated_mpmap_block.h").read_text(encoding="utf-8")
    for m in re.finditer(r'\{\{0x([0-9A-F]{8})u, 0x([0-9A-F]{8})u, 0x([0-9A-F]{8})u, 0x([0-9A-F]{8})u\}, (\d+), 0x[0-9A-F]{8}u, \d+, "(\w+)"\}', text):
        block["-".join(m.group(i) for i in range(1, 5))] = (int(m.group(5)), m.group(6))
    seen, queue = set(), deque(ROOTS)
    while queue:
        g = queue.popleft()
        if g in seen or g in NOT_FOLLOWED:
            continue
        seen.add(g)
        for ref in ents.get(g, ("", ()))[1]:
            if ref in ents and ref not in seen:
                queue.append(ref)
    rows = []
    for g in seen:
        if g not in block:
            continue
        group, cls = block[g]
        if group in OPEN_GROUPS or cls.startswith("UI"):
            continue
        rows.append((cls, g))
    rows.sort()
    lines = [
        "// Generated by tools/build_versus_templates.py from analysis/catalog/entities.jsonl.",
        "// global_mp_assets records a Versus round spawns from at run time: their records",
        "// stay on an MP map, the map's own instances are refused (runtime_coop_mpmap.inc).",
        "#pragma once",
        "namespace coop_mpmap {",
        "struct VersusTemplate { uint32_t guid[4]; const char* cls; };",
        "inline constexpr VersusTemplate kVersusTemplates[] = {",
    ]
    for cls, g in rows:
        words = ", ".join("0x%sU" % w for w in g.split("-"))
        lines.append('    {{%s}, "%s"},' % (words, cls))
    lines += ["};", "}  // namespace coop_mpmap", ""]
    (root / "src/generated_versus_templates.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote src/generated_versus_templates.h:", len(rows), "templates")
    for cls, g in rows:
        print("  %-24s %s" % (cls, g))


if __name__ == "__main__":
    main()
