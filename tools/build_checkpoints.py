r"""Build src/generated_checkpoints.h from the game's map.txt (the debug level list).

A map.txt line: <level key> [/MULTIPLAYER] [/UNIFORM <guid name>] /FOLDER <folder>
/STREAMLIST <stream> /CHECKPOINT <name> <guid name> <name> <guid name> ...
Only the campaign is kept (folder ds_2\, not multiplayer).

A guid name is "X" + 8 letters + 1 letter + "_" + 7 hex + "_" + 7 hex + "_v3":
the 8 letters are words 2 and 3 of the GUID (little endian), the 9th letter
is the first byte of word 0, and the 14 hex digits are the rest of words 0
and 1. transition_zone_04 XPRICE0021_CB0696B_5B8F4B5_v3 is the Checkpoint
31CB0696-B5B8F4B5-43495250-32303045 of the catalog.

usage: python tools/build_checkpoints.py [map.txt]
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from ds2_paths import MODDING_TOOLS  # noqa: E402

MAP_TXT = Path(sys.argv[1]) if len(sys.argv) > 1 else MODDING_TOOLS / "port_build" / "dat0_contents" / "map.txt"
CATALOG = ROOT / "analysis" / "catalog" / "entities.jsonl"
OUT = ROOT / "src" / "generated_checkpoints.h"
NAME = re.compile(r"^X(.{8})(.)_([0-9A-F]{7})_([0-9A-F]{7})_v\d+$", re.I)


def decode(text):
    m = NAME.match(text)
    if not m:
        return None
    letters, byte, a, b = m.groups()
    raw = letters.encode("latin-1")
    w0 = int("%02X%s" % (ord(byte), a[:6]), 16)
    w1 = int(a[6:] + b, 16)
    return "%08X-%08X-%08X-%08X" % (w0, w1, int.from_bytes(raw[:4], "little"), int.from_bytes(raw[4:], "little"))


def chapter_label(key):
    m = re.match(r"ch(\d+)_", key)
    return "CH%02d" % int(m.group(1)) if m else key.upper()


def main():
    chapters, rows, bad = [], [], []
    for line in MAP_TXT.read_text(encoding="latin-1").splitlines():
        tokens = line.split()
        if len(tokens) < 2:
            continue
        key, rest = tokens[0], tokens[1:]
        opts, i = {}, 0
        checkpoints = []
        while i < len(rest):
            t = rest[i].upper()
            if t == "/MULTIPLAYER":
                opts["mp"] = True
                i += 1
            elif t in ("/UNIFORM", "/FOLDER", "/STREAMLIST"):
                opts[t[1:].lower()] = rest[i + 1] if i + 1 < len(rest) else ""
                i += 2
            elif t == "/CHECKPOINT":
                pairs = rest[i + 1:]
                for k in range(0, len(pairs) - 1, 2):
                    checkpoints.append((pairs[k], pairs[k + 1]))
                break
            else:
                i += 1
        if opts.get("mp") or opts.get("folder", "").lower().rstrip("\\") != "ds_2" or not checkpoints:
            continue
        uniform = decode(opts["uniform"]) if "uniform" in opts else None
        first = len(rows)
        for name, guid_name in checkpoints:
            guid = decode(guid_name)
            if not guid:
                bad.append((key, name, guid_name))
                continue
            rows.append((len(chapters), name, guid, guid_name))
        chapters.append((key, chapter_label(key), opts.get("streamlist", "ds_2.str"), uniform, first, len(rows) - first))
    # how many of them the catalog knows as Checkpoint objects
    known = set()
    wanted = {r[2] for r in rows}
    if CATALOG.exists():
        for line in open(CATALOG, encoding="utf-8"):
            if '"Checkpoint"' not in line:
                continue
            g = json.loads(line).get("guid")
            if g in wanted:
                known.add(g)
    for c in chapters:
        print("%-10s %s %-9s uniform %s: %d checkpoints" % (c[0], c[1], c[2], c[3] or "-", c[5]))
    print("%d chapters, %d checkpoints, %d in the catalog, %d names not decoded %s" % (len(chapters), len(rows), len(known), len(bad), bad[:4]))

    def words(g):
        return "{%s}" % ",".join("0x%sU" % w for w in g.split("-"))

    text = [
        "// Generated by tools/build_checkpoints.py from the game's map.txt (the debug level list).",
        "// Campaign levels only (folder ds_2). Do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "namespace ds2checkpoints {",
        "struct Chapter { const char* key; const char* label; const char* stream; bool hasUniform; uint32_t uniform[4]; unsigned first, count; };",
        "struct Checkpoint { unsigned chapter; const char* name; uint32_t guid[4]; bool inCatalog; };",
        "inline constexpr Chapter kChapters[] = {",
    ]
    for c in chapters:
        text.append("    {\"%s\", \"%s\", \"%s\", %s, %s, %d, %d}," % (c[0], c[1], c[2], "true" if c[3] else "false", words(c[3] or "00000000-00000000-00000000-00000000"),
                                                                 c[4], c[5]))
    text.append("};")
    text.append("inline constexpr Checkpoint kCheckpoints[] = {")
    for r in rows:
        text.append("    {%d, \"%s\", %s, %s},   // %s" % (r[0], r[1], words(r[2]), "true" if r[2] in known else "false", r[3]))
    text += [
        "};",
        "inline constexpr unsigned kChapterCount = sizeof(kChapters) / sizeof(kChapters[0]);",
        "inline constexpr unsigned kCheckpointCount = sizeof(kCheckpoints) / sizeof(kCheckpoints[0]);",
        "}  // namespace ds2checkpoints",
        "",
    ]
    OUT.write_text("\n".join(text), encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
