"""analysis/ds2_message_names_live_2026-09-17.json -> src/generated_message_names.h

A sorted {hash, name} table so the plugin can print a message's name in the
log and the INI can list messages by name (see coop_names::Name).
"""
import json
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
names = json.load(open(os.path.join(root, "analysis", "ds2_message_names_live_2026-09-17.json")))
rows = sorted((int(h, 16), n) for h, n in names.items() if n)
with open(os.path.join(root, "src", "generated_message_names.h"), "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/embed_message_names.py. Do not edit.\n#pragma once\n#include <cstdint>\n")
    f.write("namespace coop_names {\nstruct Entry { uint32_t hash; const char* name; };\n")
    f.write("constexpr Entry kEntries[] = {\n")
    for h, n in rows:
        safe = n.replace("\\", "\\\\").replace('"', '\\"')
        f.write('    {0x%08Xu, "%s"},\n' % (h, safe))
    f.write("};\nconstexpr unsigned kCount = %d;\n" % len(rows))
    f.write("inline const char* Name(uint32_t hash) {\n"
            "    unsigned lo = 0, hi = kCount;\n"
            "    while (lo < hi) {\n"
            "        const unsigned mid = (lo + hi) / 2;\n"
            "        if (kEntries[mid].hash < hash) lo = mid + 1; else hi = mid;\n"
            "    }\n"
            "    return (lo < kCount && kEntries[lo].hash == hash) ? kEntries[lo].name : \"\";\n"
            "}\n}  // namespace coop_names\n")
print("entries", len(rows))
