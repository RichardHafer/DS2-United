"""Embed the message an enemy sends when it dies.

A scripted room does not count corpses, it counts messages. Each authored enemy
carries one on its health component (`CMD_SetOnDeathMessage`), and the level
waits for it: the four slashers in the hospital lobby all send
`hospital_lobby_slasher_dead`, and names like `var_op_slasher_count_decre` say
plainly what the listener does with it.

A replacement is a different entity and carries the donor's message instead, so
the room's counter never reaches zero and the door stays shut. That is what every
stuck quarantine in this project has been. 616 of 1082 catalogued enemies carry
such a message, 316 of the 405 that arrive through a vent.

The runtime needs both sides: what the level expected, and what the donor will
send unless something is done about it.
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def name_hash(text):
    """The engine's own string hash: h = h * 0x1003F + lowercase(c)."""
    value = 0
    for char in text.lower():
        value = (value * 0x1003F + ord(char)) & 0xFFFFFFFF
    return value


def main():
    with (ROOT / "analysis/catalog/enemy_targets.tsv").open(newline="", encoding="utf-8") as f:
        targets = {r["guid"]: r for r in csv.DictReader(f, delimiter="\t")}
    index = {(r["archive"], r["asset"], int(r["entity_index"])): g for g, r in targets.items()}

    # The field is a self-relative string pointer (flags 17), so the number in
    # the archive is a file offset and means nothing at runtime; embedding it
    # was the reason the first attempt reported not_found every single time.
    # The name is what survives, so both the name and the engine's hash of it go
    # into the table and the runtime can look for either.
    #
    # Four authored fields on an enemy are messages the level listens for, and
    # they behave the same way: the level waits, the donor sends something else.
    # The death message dominates at 616 carriers, but a room that waits for
    # "the spawn finished" (39) or "it noticed you" (35) hangs just as hard.
    WANTED = ("CMD_SetOnDeathMessage", "CMD_SetOnHealthModifiedMsg",
              "CMD_SetSpawnDoneSendMessage", "MSG_AWARE")
    messages = {}
    with (ROOT / "analysis/catalog/entities.jsonl").open(encoding="utf-8") as f:
        for line in f:
            entity = json.loads(line)
            guid = index.get((entity["archive"], entity["asset"], entity["index"]))
            if not guid:
                continue
            for image in entity.get("images", []):
                for field in image.get("fields", []):
                    if field.get("name") not in WANTED:
                        continue
                    value = field.get("value")
                    if isinstance(value, int) and value:
                        messages.setdefault(guid, {})[field["name"]] = (
                            value, field.get("string_candidate") or "")

    lines = ["// Generated by tools/embed_death_messages.py.", "#pragma once",
             "namespace ds2 {",
             "// The messages this enemy sends that a level may be listening for: its",
             "// death, a health change, the end of its spawn, and noticing the player.",
             "// A scripted room counts those, so a replacement has to send the ones the",
             "// level is waiting for and not the ones its donor was authored with.",
             "// Each message is carried twice: the authored name, and the engine's",
             "// hash of it. The runtime does not know yet which of the two the header",
             "// holds, so it looks for both and reports which one it found.",
             "struct DeathMessageRow { Guid guid; ScriptMessage death, healthModified, spawnDone, aware; };",
             "inline constexpr DeathMessageRow kDeathMessages[] = {"]
    for guid, fields in sorted(messages.items()):
        words = ",".join("0x%su" % word for word in guid.split("-"))
        def cell(field):
            name = fields.get(field, (0, ""))[1]
            return '{%s,0x%08Xu}' % (json.dumps(name), name_hash(name) if name else 0)
        lines.append("    {{%s},%s,%s,%s,%s}," % (
            words, cell("CMD_SetOnDeathMessage"), cell("CMD_SetOnHealthModifiedMsg"),
            cell("CMD_SetSpawnDoneSendMessage"), cell("MSG_AWARE")))
    lines += ["};", "}", ""]
    out = ROOT / "src/generated_death_messages.h"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("embedded %d enemies with script messages -> %s" % (len(messages), out))


if __name__ == "__main__":
    main()
