"""Embed the store chapter of every schematic reward in the randomized pool.

The store adds an item once CMD_SetMinLevelReq <= the current chapter, found
or not (PlayerStore::AddItem, gate at 0x00BB5A1D). A shuffled schematic
therefore came back through the store a chapter or two later. The runtime
gives each reward the store chapter of the place its schematic now lies at,
which needs the authored values of all rewards.

    python tools/build_schematic_store_levels.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "analysis" / "schematics" / "schematic_catalog.json"
ENTITIES = ROOT / "analysis" / "catalog" / "entities.jsonl"
HEADER = ROOT / "src" / "generated_schematic_store_levels.h"
KIOSK_LIST = "58C8CB2B-919105AA-3045454C-58373634"   # ItemStoreList of every kiosk from ch02_ase on


def main():
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    rewards = {d["reward_guid"]: d["reward_name"] for d in catalog["definitions"] if d["status"] == "base_story_candidate"}
    levels, kiosk = {}, None
    for line in ENTITIES.open(encoding="utf-8"):
        start = line.find('"guid": "') + 9
        guid = line[start:start + 35]
        if guid not in rewards and guid != KIOSK_LIST:
            continue
        row = json.loads(line)
        fields = [f for image in row.get("images", []) for f in image.get("fields", [])]
        if guid == KIOSK_LIST:
            listed = {f.get("guid_candidate") for f in fields if f.get("name") == "m_ItemDataArr"}
            if kiosk is not None and listed != kiosk:
                raise ValueError("kiosk list instances differ")
            kiosk = listed
            continue
        for f in fields:
            if f.get("name") == "CMD_SetMinLevelReq":
                levels.setdefault(guid, set()).add(f.get("value"))
    if kiosk is None:
        raise ValueError("kiosk list not found")
    lines = ["// Generated by tools/build_schematic_store_levels.py.", "#pragma once",
             '#include "schematic_policy.h"', "", "namespace ds2::schematics {",
             "struct StoreLevel { Guid reward; int minLevel; const char* name; };",
             "inline constexpr StoreLevel kStoreLevels[] = {"]
    for guid, name in sorted(rewards.items(), key=lambda kv: kv[1]):
        values = levels.get(guid)
        if not values or len(values) != 1:
            raise ValueError(f"{name} {guid}: MinLevelReq {values}")
        if guid not in kiosk:
            raise ValueError(f"{name} {guid}: not in the kiosk list")
        words = ", ".join(f"0x{w}u" for w in guid.split("-"))
        lines.append(f"    {{{{{{{words}}}}}, {next(iter(values))}, {json.dumps(name)}}},")
    lines += ["};", "}  // namespace ds2::schematics", ""]
    HEADER.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(rewards)} rewards, all in the kiosk list")


if __name__ == "__main__":
    main()
