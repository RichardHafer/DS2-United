"""Embed the bench upgrade node catalog for the runtime.

The catalog carries identity only: which tree a node belongs to, its name hash,
and whether that name is used by exactly one tree. It deliberately does not
carry node types. The runtime asks the game's own hash-to-type function for
those at install time, so a wrong offline guess cannot reach the permutation.

Hash function, read from retail 0x007423C0:

    h = 0
    for c in name:
        if 'A' <= c <= 'Z': c = c + 0x20
        h = (h * 0x1003F + c) & 0xFFFFFFFF

Verified: hash("HP") == 0x681A08, which 0x00B76990 maps to NODE_HP (7).
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

HASH_MULTIPLIER = 0x1003F


def name_hash(name):
    value = 0
    for char in name.encode("ascii"):
        if 0x41 <= char <= 0x5A:
            char += 0x20
        value = (value * HASH_MULTIPLIER + char) & 0xFFFFFFFF
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path,
                        default=Path(__file__).resolve().parents[1] / "analysis/upgrades/upgrade_catalog.json")
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "src/generated_bench_catalog.h")
    args = parser.parse_args()

    catalog = json.loads(args.catalog.read_text(encoding="utf-8"))
    trees = [name for name, data in sorted(catalog["items"].items()) if data["permutable"]]

    owners = defaultdict(set)
    for item in trees:
        for node in catalog["items"][item]["nodes"]:
            if node["x"] is not None:
                owners[node["name"]].add(item)

    rows = []
    seen = set()
    for index, item in enumerate(trees):
        for node in catalog["items"][item]["nodes"]:
            if node["x"] is None:
                continue
            digest = name_hash(node["name"])
            # One entry per (tree, name). A name shared by several trees appears
            # once per tree and is marked so the per-tree pass skips it.
            key = (index, digest)
            if key in seen:
                continue
            seen.add(key)
            # A name used by um:BaseValue carries that tree's authored base for
            # the stat. Remapping it moves the base value, which is how the RIG
            # ended up with no health at all.
            carries = node["name"] in catalog["items"][item]["baseValues"]
            rows.append((index, digest, len(owners[node["name"]]) == 1,
                         bool(node["startPoint"]), carries, item, node["name"]))

    collisions = defaultdict(set)
    for _, digest, _, _, _, _, name in rows:
        collisions[digest].add(name)
    clashing = {d: names for d, names in collisions.items() if len(names) > 1}

    lines = ["#pragma once",
             "// Generated by tools/embed_bench_catalog.py. Identity only, no node types.",
             "#include <cstdint>",
             "",
             "namespace ds2::bench {",
             "struct TreeName { const char* name; };",
             "inline constexpr TreeName kTrees[] = {"]
    for item in trees:
        lines.append('    {"%s"},' % item)
    lines += ["};",
              "",
              "// uniqueToTree: this name is authored in exactly one tree, so remapping it",
              "// cannot reach another tree.",
              "struct BenchNode { uint16_t tree; uint32_t nameHash; bool uniqueToTree; bool startPoint;",
              "                   bool carriesBaseValue; };",
              "inline constexpr BenchNode kBenchNodes[] = {"]
    for index, digest, unique, start, carries, item, name in rows:
        lines.append("    {%2d, 0x%08Xu, %-5s, %-5s, %-5s},  // %s / %s" %
                     (index, digest, "true" if unique else "false",
                      "true" if start else "false", "true" if carries else "false", item, name))
    lines += ["};", "}  // namespace ds2::bench", ""]

    args.output.write_text("\n".join(lines), encoding="utf-8")

    unique = sum(1 for r in rows if r[2])
    print(f"Embedded {len(rows)} bench nodes across {len(trees)} trees; "
          f"{unique} unique to their tree, {len(rows) - unique} shared")
    if clashing:
        for digest, names in clashing.items():
            print(f"hash collision {digest:08X}: {sorted(names)}")
        raise SystemExit("hash collision between distinct node names")
    print("no hash collisions between distinct node names")


if __name__ == "__main__":
    main()
