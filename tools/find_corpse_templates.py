"""Find enemy templates the level authors with CMD_SetHealth 0.

Such a template spawns as a corpse on purpose. The ch11 convergence spawns one
every few seconds, lets a gravity field pull it into the Marker and deletes it
on a trigger. A living replacement never reaches that trigger, so the loop
piles up enemies until the game crashes (eyepoke scene).

    python tools/find_corpse_templates.py            report
    python tools/find_corpse_templates.py --write    also writes src/generated_corpse_templates.h
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "analysis" / "catalog" / "entities.jsonl"
ENEMIES = ROOT / "src" / "generated_enemy_catalog.h"
HEADER = ROOT / "src" / "generated_corpse_templates.h"


def enemy_guids():
    text = ENEMIES.read_text(encoding="utf-8")
    row = re.compile(r"\{\{0x([0-9A-F]{8})u,0x([0-9A-F]{8})u,0x([0-9A-F]{8})u,0x([0-9A-F]{8})u\},\{")
    return {"-".join(m.groups()) for m in row.finditer(text)}


def corpses():
    enemies = enemy_guids()
    found = {}
    for line in CATALOG.open(encoding="utf-8"):
        if "CMD_SetHealth" not in line:
            continue
        row = json.loads(line)
        if row["guid"] not in enemies:
            continue
        for image in row.get("images", []):
            if not image.get("class", "").endswith("HealthComponent"):
                continue
            for field in image.get("fields", []):
                if field.get("name") == "CMD_SetHealth" and field.get("value") == 0:
                    found[row["guid"]] = (row["images"][0].get("class", ""), row["archive"])
    return sorted(found.items())


def write_header(rows):
    lines = ["// Generated by tools/find_corpse_templates.py, do not edit.",
             "#pragma once",
             "namespace ds2 {",
             "struct CorpseTemplate { Guid guid; const char* name; };",
             "inline constexpr CorpseTemplate kCorpseTemplates[] = {"]
    for guid, (cls, archive) in rows:
        words = ",".join("0x%su" % w for w in guid.split("-"))
        name = "%s %s" % (cls, archive.replace("\\", "/").split("/")[-1])
        lines.append("    {{%s}, %s}," % (words, json.dumps(name)))
    lines += ["};", "}", ""]
    HEADER.write_text("\n".join(lines), encoding="utf-8")


def main():
    rows = corpses()
    for guid, (cls, archive) in rows:
        print("%s %-10s %s" % (guid, cls, archive))
    print("%d corpse templates" % len(rows))
    if "--write" in sys.argv:
        write_header(rows)


if __name__ == "__main__":
    main()
