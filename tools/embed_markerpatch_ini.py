"""Turn third_party\\MarkerPatch-United\\MarkerPatch.ini into a C++ header for the edition.

    python -I tools/embed_markerpatch_ini.py <MarkerPatch.ini> <out header>

The United edition writes these bytes when the game folder has no MarkerPatch.ini.
"""
import sys
from pathlib import Path


def main():
    data = Path(sys.argv[1]).read_bytes()
    rows = []
    for at in range(0, len(data), 24):
        rows.append("    " + ", ".join("0x%02X" % b for b in data[at:at + 24]) + ",")
    text = ("// Generated by tools/embed_markerpatch_ini.py from third_party/MarkerPatch-United/MarkerPatch.ini.\n"
            "#pragma once\n"
            "static const unsigned char kUnitedDefaultIni[] = {\n" + "\n".join(rows) + "\n};\n")
    Path(sys.argv[2]).write_bytes(text.encode("ascii"))
    print("embedded %d bytes into %s" % (len(data), sys.argv[2]))


if __name__ == "__main__":
    main()
