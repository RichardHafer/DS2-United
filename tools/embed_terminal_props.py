"""Collect unambiguous retail campaign placements for lethal prop hit retries."""
import json
import re
from collections import Counter
from pathlib import Path

root = Path(__file__).resolve().parents[1]
counts = Counter()
placed = set()
with (root / "analysis/catalog/entities.jsonl").open(encoding="utf-8") as records:
    for line in records:
        entity = json.loads(line)
        guid = entity["guid"]
        counts[guid] += 1
        path = entity["asset"].lower().split("\\")
        if (len(path) > 2 and path[0] == "levels" and re.fullmatch(r"ch[0-9]+_[a-z0-9_]+", path[1])
                and entity["spawn_flags"] == 1 and entity["images"] and entity["images"][0]["class"] == "DamageableProp"):
            placed.add(guid)

unique = sorted(guid for guid in placed if counts[guid] == 1)
if not unique:
    raise ValueError("No unique DamageableProp placements in the catalog")
lines = ["// Generated by tools/embed_terminal_props.py from the retail campaign.", 
         "constexpr uint32_t kPlacedGuids[][4] = {"]
for guid in unique:
    lines.append("    {" + ", ".join(f"0x{int(word, 16):08X}u" for word in guid.split("-")) + "},")
lines.append("};")
(root / "src/generated_terminal_props.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Verified {len(unique)} unique campaign DamageableProp placements.")
