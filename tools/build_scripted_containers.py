"""Find containers the level logic hangs on.

A StandardContainer that sends messages when it opens (CMD_OpenStart,
CMD_OpenPressed, CMD_OpenContainer, CMD_OpenFinish) or can be locked by a
script (CMD_LockContainer), and a BreakableContainer with a death target, a grab
message or a group, are part of a scripted event. The companion bots leave those
shut ([Bot] LootContainers, runtime_coop_bot.inc).

    python tools/build_scripted_containers.py            report
    python tools/build_scripted_containers.py --write    also writes src/generated_scripted_containers.h
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "analysis" / "catalog" / "entities.jsonl"
HEADER = ROOT / "src" / "generated_scripted_containers.h"
CLASSES = ("StandardContainer", "BreakableContainer")
WIRED = {"CMD_OpenStart", "CMD_OpenPressed", "CMD_OpenContainer", "CMD_OpenFinish", "CMD_LockContainer", "CMD_SetDeathTarget", "CMD_GrabMsg",
         "CMD_SetGroup"}


def scan():
    found, counts = [], {c: 0 for c in CLASSES}
    for line in CATALOG.open(encoding="utf-8"):
        if "Container" not in line:
            continue
        row = json.loads(line)
        images = row.get("images", [])
        if not images or images[0].get("class") not in CLASSES:
            continue
        cls = images[0]["class"]
        counts[cls] += 1
        names = {f.get("name") for image in images for f in image.get("fields", [])}
        hit = sorted(n for n in names & WIRED if n)
        if hit:
            found.append((row["guid"], cls, hit, row["archive"]))
    return sorted(found), counts


def write_header(rows):
    lines = ["// Generated by tools/build_scripted_containers.py. Do not edit.",
             "#pragma once",
             "#include <cstdint>",
             "namespace ds2 {",
             "struct ScriptedContainer { uint32_t guid[4]; const char* why; };",
             "inline constexpr ScriptedContainer kScriptedContainers[] = {"]
    for guid, cls, hit, archive in rows:
        words = ",".join("0x%su" % w for w in guid.split("-"))
        why = "%s %s %s" % (cls, "+".join(hit), archive.replace("\\", "/").split("/")[-1])
        lines.append("    {{%s}, %s}," % (words, json.dumps(why)))
    lines += ["};", "}", ""]
    HEADER.write_text("\n".join(lines), encoding="utf-8")


def main():
    rows, counts = scan()
    for guid, cls, hit, archive in rows:
        print("%s %-18s %-40s %s" % (guid, cls, ",".join(hit), archive))
    print("%d scripted of %s" % (len(rows), counts))
    if "--write" in sys.argv:
        write_header(rows)


if __name__ == "__main__":
    main()
