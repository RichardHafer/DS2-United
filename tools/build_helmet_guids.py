"""Every suit's helmet prop GUID (Uniform CMD_SetUniformHelmetGUID).

A helmet is its own prop, and every player wearing that suit has one with the
same GUID. The co-op deletion mirror (runtime_coop_removals.inc) removes objects
by GUID, so it must never touch these.

Writes src/generated_helmet_guids.h.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]


def main():
    helmets = set()
    with (root / "analysis/catalog/entities.jsonl").open(encoding="utf-8") as f:
        for line in f:
            if "CMD_SetUniformHelmetGUID" not in line:
                continue
            e = json.loads(line)
            for img in e["images"]:
                for fl in img["fields"]:
                    if fl["name"] == "CMD_SetUniformHelmetGUID" and fl.get("guid_candidate"):
                        helmets.add(fl["guid_candidate"].upper())
    lines = [
        "// Generated by tools/build_helmet_guids.py from analysis/catalog/entities.jsonl.",
        "// Every suit's helmet prop GUID: shared by every player wearing that suit.",
        "#pragma once",
        "namespace coop_removals_data {",
        "inline constexpr uint32_t kHelmetGuids[][4] = {",
    ]
    for g in sorted(helmets):
        lines.append("    {%s}," % ", ".join("0x%sU" % w for w in g.split("-")))
    lines += ["};", "}  // namespace coop_removals_data", ""]
    (root / "src/generated_helmet_guids.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote src/generated_helmet_guids.h:", len(helmets), "helmets")


if __name__ == "__main__":
    main()
