"""The player spawn points of the multiplayer maps and when each one is in use.

A MultiplayerSpawnPoint is active from m_activateMessage (none: from the start)
until m_deactivateMessage (none: to the end). Marker Lab moves its humans from
the start area to the power area at obj_1_complete and on to c_lab at
obj_3_complete. The co-op respawn (runtime_coop_respawn.inc) puts a player back
on a point that is active now, near the team.

The Outbreak maps' points come from their baked images (tools/mp_baked.py).

Writes src/generated_mp_spawn_windows.h.
"""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
catalog = root / "analysis/catalog"
MAPS = {"mp_bombrun": "mp_bombRun", "mp_detonate": "mp_detonate", "mp_escape": "mp_escape",
        "mp_gov": "mp_gov", "mp_solar": "mp_solar"}
FIELDS = ("m_activateMessage", "m_deactivateMessage")
FLAGS = ("m_initiallyActive", "m_validForInitialSpawn", "m_validForRespawn")   # 1 when not authored


def map_of(archive):
    for key, name in MAPS.items():
        if "\\" + key + "\\" in archive.lower():
            return name
    return None


def name_hash(text):
    # the engine's message name hash: h * 0x1003F + lower-case char
    h = 0
    for c in text.lower():
        h = (h * 0x1003F + ord(c)) & 0xFFFFFFFF
    return h


def cbool(v):
    return "true" if v else "false"


def cguid(text):
    return "{" + ",".join(f"0x{int(w, 16):08X}u" for w in text.split("-")) + "}"


points = []
with (catalog / "entities.jsonl").open(encoding="utf-8") as stream:
    for line in stream:
        if "MultiplayerSpawnPoint" not in line:
            continue
        entity = json.loads(line)
        name = map_of(entity["archive"])
        images = entity.get("images", [])
        if not name or not images or images[0].get("class") != "MultiplayerSpawnPoint":
            continue
        fields, flags = {}, {}
        for image in images:
            for field in image.get("fields", []):
                if field.get("name") in FIELDS and field.get("string_candidate"):
                    fields[field["name"]] = field["string_candidate"]
                elif field.get("name") in FLAGS:
                    flags[field["name"]] = int(field.get("value", 1)) != 0
        points.append((name, entity["guid"].upper(), fields.get(FIELDS[0], ""), fields.get(FIELDS[1], ""),
                       flags.get(FLAGS[0], True), flags.get(FLAGS[1], True), flags.get(FLAGS[2], True)))

# The Outbreak maps: baked images carry every value, so no defaults apply. A point
# whose message name cannot be read back is left out.
sys.path.insert(0, str(root / "tools"))
import mp_baked  # noqa: E402
skipped = []
for e in mp_baked.iter_baked_entities({"MultiplayerSpawnPoint"}):
    blob = e["blob"]
    on = mp_baked.message_at(blob, mp_baked.SPAWNPOINT_ON)
    off = mp_baked.message_at(blob, mp_baked.SPAWNPOINT_OFF)
    if (on[0] and not on[1]) or (off[0] and not off[1]):
        skipped.append(f"{e['map']} {e['guid']}: window message without a readable name")
        continue
    points.append((e["map"], e["guid"], on[1], off[1], blob[mp_baked.SPAWNPOINT_ACTIVE] != 0,
                   blob[mp_baked.SPAWNPOINT_INITIAL] != 0, blob[mp_baked.SPAWNPOINT_RESPAWN] != 0))
points.sort()

lines = [
    "// Generated by tools/build_mp_spawn_windows.py from analysis/catalog and the",
    "// Outbreak maps' baked images (tools/mp_baked.py).",
    "// The MP maps' player spawn points: active from onName (empty: from the start",
    "// when initiallyActive) until offName (empty: the end); on/off are the message",
    "// name hashes. respawn: m_validForRespawn (Titan Mines' four start points are not).",
    "#pragma once",
    "#include <cstdint>",
    "namespace coop_spawnwin {",
    "struct Row { const char* map; uint32_t guid[4]; uint32_t on, off; bool initiallyActive, initial, respawn; const char* onName; const char* offName; };",
    "inline constexpr Row kRows[] = {",
]
for name, guid, on, off, active, initial, respawn in points:
    lines.append(f'    {{"{name}",{cguid(guid)},{f"0x{name_hash(on):08X}u" if on else "0u"},{f"0x{name_hash(off):08X}u" if off else "0u"},'
                 f'{cbool(active)},{cbool(initial)},{cbool(respawn)},"{on}","{off}"}},')
lines += ["};", "}  // namespace coop_spawnwin", ""]
out = root / "src/generated_mp_spawn_windows.h"
out.write_bytes("\n".join(lines).encode("utf-8"))
by_map = {}
for name, _, on, off, active, initial, respawn in points:
    key = (on or ("start" if active else "never"), off or "end", "" if respawn else " (not for respawns)")
    by_map.setdefault(name, {}).setdefault(key, 0)
    by_map[name][key] += 1
print(f"wrote {out.relative_to(root)} points={len(points)}")
for name in sorted(by_map):
    print(name, ", ".join(f"{a}..{b}{c} x{n}" for (a, b, c), n in sorted(by_map[name].items())))
for line in skipped:
    print("outbreak left out:", line)
# runtime_coop_spawnwin.inc reads an initiallyActive point with an on message as
# closed until that message comes; the stock maps have none such
for name, guid, on, off, active, _, _ in points:
    if on and active:
        print(f"note: {name} {guid} is initially active and also has on={on}")
watched = {h for p in points for h in (p[2], p[3]) if h}
print(f"spawn windows watch {len(watched)} message(s) (runtime_coop_spawnwin.inc kMax 32)")
