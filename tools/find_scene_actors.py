"""Write src/generated_scene_actors.h: FuncSpawn targets a story scene refers to.

A scene names its actors by GUID. MoreEnemies leaves these spawns alone when
[DS2Randomizer] MoreEnemiesSkipScripted=1: a copy of a scene actor is not in the
scene and roams where the level never has one (12.10., saferoom slasher x4).
Only story events and in-game cinematics count (sequences named se_*/igc_*):
combat entrances (tube slashers, crawler holes) stay multiplied. A target whose
own messages feed such a scene counts too: Ellie's two vent slashers in the
street scene are not named by it, but their deaths interrupt it.
"""
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CATALOG = REPO / "analysis" / "catalog" / "entities.jsonl"
OUT = REPO / "src" / "generated_scene_actors.h"
STORY = re.compile(r"^(ss_)?(se|igc)_")
DEATH_MESSAGES = REPO / "src" / "generated_death_messages.h"
STORY_MESSAGE = re.compile(r"(^|_)(se|igc)_\d|^interrupt_")
MESSAGE_ROW = re.compile(r"\{\{0x([0-9A-F]+)u,0x([0-9A-F]+)u,0x([0-9A-F]+)u,0x([0-9A-F]+)u\},(.*)\},?\s*$", re.M)


def message_bound():
    """Targets that send a message a story scene waits for."""
    found = set()
    for row in MESSAGE_ROW.finditer(DEATH_MESSAGES.read_text(encoding="utf-8")):
        names = re.findall(r'\{"([^"]+)",0x', row.group(5))
        if any(STORY_MESSAGE.search(n.lower()) for n in names):
            found.add("-".join(row.group(i) for i in range(1, 5)))
    return found


def main():
    targets = {}
    scene_refs = set()
    with CATALOG.open(encoding="utf-8") as f:
        for line in f:
            if '"FuncSpawn"' not in line and '"ScriptedSequence"' not in line:
                continue
            record = json.loads(line)
            image = record["images"][0]
            if image["class"] == "FuncSpawn":
                for field in image["fields"]:
                    if field["name"] == "CMD_SetSpawnTarget" and field.get("guid_candidate"):
                        targets.setdefault(field["guid_candidate"].upper(), record["guid"])
            elif image["class"] == "ScriptedSequence":
                name = next((x.get("string_candidate") for x in image["fields"] if x["name"] == "CMD_SetTargetName"), "") or ""
                if not STORY.match(name.lower()):
                    continue
                for field in image["fields"]:
                    if field.get("guid_candidate"):
                        scene_refs.add(field["guid_candidate"].upper())
    bound = message_bound()
    actors = sorted(g for g in targets if g in scene_refs or g in bound)
    rows = []
    for g in actors:
        parts = [int(p, 16) for p in g.split("-")]
        rows.append("    {{0x%08Xu,0x%08Xu,0x%08Xu,0x%08Xu}}," % tuple(parts))
    text = ["// Generated by tools/find_scene_actors.py, do not edit.",
            "#pragma once",
            "namespace ds2 {",
            "// FuncSpawn targets a story scene (se_*/igc_* sequence) refers to or waits for, sorted.",
            "inline constexpr Guid kSceneActors[] = {"] + rows + ["};", "}  // namespace ds2", ""]
    OUT.write_text("\n".join(text), encoding="utf-8")
    print("scene actors: %d of %d spawn targets (%d by their messages) -> %s" % (len(actors), len(targets), len(bound), OUT))


if __name__ == "__main__":
    sys.exit(main())
