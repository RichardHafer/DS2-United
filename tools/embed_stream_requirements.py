"""Embed exact requirements for the private research stream."""
import json
import hashlib
from pathlib import Path
from stream_framing import validate_framing

root = Path(__file__).resolve().parents[1]
stream_directory = root / "analysis/runtime_stream"
manifest = json.loads((stream_directory / "ds2_randomizer_pool.toc.json").read_text())
# The randomizer's own model streams (a skin's ds2_randomizer_<variant>) are forced by the
# pool's TOC and load with it, so they are not prerequisites the plugin waits
# for before requesting the pool.
entries = manifest["shared"] + [e for e in manifest["forced"] if not e[1].startswith("ds2_randomizer_")]
if len({name for _, name in entries}) != len(entries):
    raise ValueError("Duplicate stream prerequisites")
lines = ["// Generated by tools/embed_stream_requirements.py.", "#pragma once",
         "namespace ds2 {", "struct StreamRequirement { unsigned identity; const char* name; };",
         "inline constexpr StreamRequirement kStreamRequirements[] = {"]
for identity, name in entries:
    lines.append(f"    {{0x{identity:08X}u, {json.dumps(name)}}},")
lines += ["};"]

# Which families does the pool still carry models for?  Trimming the TOC is how
# the pool stops holding packages it can never use, and a donor whose models are
# no longer forced resident would spawn as nothing at all.  So the families are
# recorded next to the requirements and the plugin refuses donors from a family
# whose package is gone, whatever the TOC happens to contain.
packages = json.loads((root / "analysis/native_character_streams.json").read_text())["packages"]
present = {name for _identity, name in manifest["forced"]}
families = {}
for package in packages:
    classes = package.get("classes") or []
    if not classes:
        continue
    # Every family a package carries, not only the first: the divider package
    # holds the core and its parts.
    for family in classes:
        families.setdefault(family, False)
        if package["toc_name"] in present:
            families[family] = True
lines += ["struct PackagedFamily { const char* family; bool resident; };",
          "inline constexpr PackagedFamily kPackagedFamilies[] = {"]
for family in sorted(families):
    lines.append(f"    {{{json.dumps(family)}, {'true' if families[family] else 'false'}}},")
# A skin's model stream is a loose file like the pool and has to be requested
# by name the same way: a TOC dependency on it is resolved against the loaded
# TOCs only and came back null (crash 45636).
# The loose files live in a folder of their own below the game root, the way
# retail packages do (global_assets\global_assets): the engine composes the
# path from the request name plus ".str", so the folder is part of the name,
# in the request and in the TOC's root name alike.
folder = "randomizer\\"
lines += ["};", f"inline constexpr const char* kStreamFolder = {json.dumps(folder)};",
          f"inline constexpr const char* kPoolStreamName = {json.dumps(folder + 'ds2_randomizer_pool')};",
          "inline constexpr const char* kModelStreams[] = {"]
for stream in manifest.get("variants", {}).get("model_streams", []):
    lines.append(f"    {json.dumps(folder + stream['name'])},")
if not manifest.get("variants", {}).get("model_streams"):
    lines.append("    nullptr,")
# The TOC root must carry the folder, or the engine drops the TOC after the
# load (see build_research_toc.STREAM_FOLDER). Refuse to embed a pool whose
# TOC would be requested under a name it does not contain.
from read_stock_toc import parse as parse_toc
toc_root = parse_toc((stream_directory / "ds2_randomizer_pool.toc").read_bytes())["entries"][0]["identity"]["name"]
if toc_root.lower() != (folder + "ds2_randomizer_pool").lower():
    raise ValueError(f"TOC root name {toc_root!r} is not the request name {folder + 'ds2_randomizer_pool'!r}; rebuild the TOC")

def zero_health_records(path):
    """Pool records whose CMD_SetHealth is 0. Such an enemy dies the moment it
    spawns and never sends its death message, so a room that counts it waits
    forever (the ch11 arena super slasher, 29.09.2026). Fix the field in the
    pool (toc.json field_patches) instead of shipping it."""
    import struct
    import sys
    from ds2_paths import MODDING_TOOLS
    sys.path.insert(0, str(MODDING_TOOLS))
    import ds2str
    import ds2_assets
    health = 0x6B435879   # CMD_SetHealth
    stream = ds2str.StreamSet(str(path))
    found, current = [], None
    for position, _tag, body in stream.chunks():
        inner = stream.tag(body[:4])
        if inner == b"SHDR":
            fields = struct.unpack_from(stream.end + "8I", body, 4)
            kind = body[36:].split(b"\0")[2] if body[36:].count(b"\0") >= 2 else b""
            current = {"kind": kind, "size": fields[7], "parts": [], "packed": False}
            if kind == b"SimGroup":
                found.append(current)
        elif inner in (b"SDAT", b"Rpak") and current is not None:
            current["packed"] |= inner != b"SDAT"
            current["parts"].append(stream.payload(body)[1])
    bad = []
    for group in found:
        data = b"".join(group["parts"])[:group["size"]]
        instances, image_at = ds2_assets.simgroup(data)
        images = ds2_assets.loose_images(data, image_at)
        for instance in instances:
            for image_id in [instance["image_id"]] + instance["component_images"]:
                for field in images.get(image_id, {}).get("fields", []):
                    if field["field_id"] == health and field["value"] == 0:
                        bad.append(instance["guid"])
    return bad


zero = zero_health_records(stream_directory / "ds2_randomizer_pool.str")
if zero:
    raise ValueError("Pool records with CMD_SetHealth 0 (they die on spawn): " + ", ".join(zero))

lines += ["};", "struct StreamProbeFile { const char* name; unsigned size; unsigned long long fingerprint; };",
          "inline constexpr StreamProbeFile kStreamProbeFiles[] = {"]
files = [("ds2_randomizer_pool", manifest)]
for stream in manifest.get("variants", {}).get("model_streams", []):
    files.append((stream["name"], stream))
for extension, digest in [("str", "stream_sha256"), ("toc", "toc_sha256")]:
  for stem, record in files:
    name = f"{stem}.{extension}"
    data = (stream_directory / name).read_bytes()
    if extension == "str":
        validate_framing(data)
    if hashlib.sha256(data).hexdigest() != record[digest]:
        raise ValueError(f"Manifest mismatch: {name}")
    fingerprint = 14695981039346656037
    for byte in data:
        fingerprint = ((fingerprint ^ byte) * 1099511628211) & 0xffffffffffffffff
    lines.append(f"    {{{json.dumps(folder + name)}, {len(data)}, 0x{fingerprint:016X}ull}},")
lines += ["};", "}", ""]
(root / "src/generated_stream_requirements.h").write_text("\n".join(lines), encoding="utf-8")
print(f"Embedded {len(entries)} private-stream prerequisites.")
