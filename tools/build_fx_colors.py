"""Writes src/generated_fx_colors.h from fxcolors/fx_color_plugin_tables.json.

The JSON comes from the offline FX colour research (analysis/DS2_FX_COLORS_2026-10-15.md): per
group the effect names with their 16-byte packed name (the first 16 bytes of every effect
buffer), and the blood textures with format, sizes, TexMod hash and the CRC32 of their first
256 bytes. The plugin (src/runtime_coop_fxcolor.inc, runtime_coop_rigcolor.inc) looks effects
up by packed name and textures by size and hash.

Usage: python -I tools/build_fx_colors.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'fxcolors' / 'fx_color_plugin_tables.json'
OUT = ROOT / 'src' / 'generated_fx_colors.h'

# group order is the enum order in the header and in runtime_coop_fxcolor.inc
WEAPONS = ['plasma_cutter', 'pulse_rifle', 'line_gun', 'contact_beam', 'ripper', 'flamethrower', 'force_gun', 'javelin',
           'detonator', 'seeker_rifle', 'rivet_gun']
GROUPS = ['stasis', 'kinesis', 'kinesis_throw', 'laser', 'blood'] + WEAPONS
RED_BAND = (330.0, 35.0)


def in_red_band(hue):
    return hue is not None and (hue >= RED_BAND[0] or hue <= RED_BAND[1])


def main():
    d = json.loads(SRC.read_text(encoding='utf-8'))
    targets = {}   # key16 -> [group, name, blood]

    def add(group, entry):
        key = bytes.fromhex(entry['key16'])
        if len(key) != 16:
            raise SystemExit('bad key for %s' % entry['name'])
        if key in targets:
            if group == 'blood':
                targets[key][2] = True   # a weapon effect with blood records
            return
        targets[key] = [group, entry['name'], group == 'blood']

    for e in d['stasis']['vfx'] + d['stasis_props']['vfx']:
        add('stasis', e)
    for e in d['kinesis']['vfx']:
        add('kinesis_throw' if e['name'] == 'tk_projectile_travel' else 'kinesis', e)
    for e in d['lasers']['vfx']:
        add('laser', e)
    for w in WEAPONS:
        for e in d['weapons'][w]['vfx']:
            add(w, e)
    for e in d['blood']['vfx']:
        add('blood', e)

    textures = []
    for t in d['blood']['textures']:
        if t['kind'] != 'coloured' or 'bile' in t['name'] or not in_red_band(t['mean_hue']):
            continue
        if t['format'] not in ('DXT1', 'DXT5'):
            raise SystemExit('unexpected format %s for %s' % (t['format'], t['name']))
        block = 8 if t['format'] == 'DXT1' else 16
        if t['total'] % block or t['level0'] % block:
            raise SystemExit('sizes of %s are no whole blocks' % t['name'])
        textures.append(t)

    lines = ['// Generated by tools/build_fx_colors.py from fxcolors/fx_color_plugin_tables.json. Do not edit.',
             '#pragma once', '#include <cstdint>', '', 'namespace ds2fx {',
             'enum Group : uint8_t { %s, kGroupCount };' % ', '.join('k' + ''.join(p.title() for p in g.split('_')) for g in GROUPS),
             'constexpr const char* kGroupNames[kGroupCount] = {%s};' % ', '.join('"%s"' % g for g in GROUPS),
             '// sorted by key; blood: the effect also has blood records (red band ones go to BloodColor)',
             'struct Effect { uint8_t key[16]; uint8_t group; bool blood; const char* name; };',
             'constexpr Effect kEffects[] = {']
    for key in sorted(targets):
        group, name, blood = targets[key]
        lines.append('    {{%s}, %d, %s, "%s"},' % (', '.join('0x%02X' % b for b in key), GROUPS.index(group), 'true' if blood else 'false', name))
    lines += ['};', 'constexpr unsigned kEffectCount = sizeof(kEffects) / sizeof(kEffects[0]);', '',
              '// prefix: CRC32 of the first 256 bytes (a cheap filter before the TexMod hash of level 0)',
              'struct BloodTexture { uint32_t hash, level0, total, prefix; bool dxt5; const char* name; };',
              'constexpr BloodTexture kBloodTextures[] = {']
    for t in sorted(textures, key=lambda t: (t['total'], t['name'])):
        lines.append('    {0x%s, %d, %d, 0x%s, %s, "%s"},' % (t['texmod_hash'], t['level0'], t['total'], t['prefix_crc256'],
                                                          'true' if t['format'] == 'DXT5' else 'false', t['name']))
    lines += ['};', 'constexpr unsigned kBloodTextureCount = sizeof(kBloodTextures) / sizeof(kBloodTextures[0]);', '}  // namespace ds2fx', '']
    OUT.write_bytes('\n'.join(lines).encode('ascii'))
    counts = {}
    for group, _, _ in targets.values():
        counts[group] = counts.get(group, 0) + 1
    print('%d effects (%s), %d with blood records; %d blood textures -> %s' % (
        len(targets), ', '.join('%s %d' % (g, counts.get(g, 0)) for g in GROUPS), sum(1 for v in targets.values() if v[2]), len(textures), OUT))


if __name__ == '__main__':
    main()
