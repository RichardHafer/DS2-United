"""Bind isolated enemy roots to their private GUIDs and exact source metadata."""
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def select_roots(graph, namespace, rows):
    identities = {tuple(item["source"]): item["destination"] for item in namespace["identities"]}
    if len(identities) != len(namespace["identities"]):
        raise ValueError("Duplicate namespaced source occurrence")
    catalog = {}
    for row in rows:
        occurrence = row["archive"], row["asset"], int(row["entity_index"])
        if occurrence in catalog:
            raise ValueError("Duplicate enemy metadata occurrence")
        catalog[occurrence] = row
    results, private = [], set()
    for root in graph["roots"]:
        node = root["nodes"][0]
        occurrence = node["archive"], node["asset"], node["index"]
        row = catalog.get(occurrence)
        destination = identities.get(occurrence)
        if not row or not destination or row["guid"] != node["guid"] or row["class"] != node["class"]:
            raise ValueError("Root occurrence does not match source metadata")
        if row["multiplayer"] != "False" or destination in private:
            raise ValueError("Invalid private root")
        private.add(destination)
        results.append({"package": root["package"], "guid": destination, "source_guid": row["guid"],
                        "family": row["class"], "model": row["model_guid"], "context": row["context"],
                        "vent": row["vent_guid"], "authored_animation": bool(row["inactive_animation"] or row["active_animation"]),
                        "ordinary": row["eligibility"] == "ordinary_candidate_unverified_swap",
                        "source": list(occurrence)})
    return results


def words(value):
    parts = value.split("-")
    if len(parts) != 4:
        raise ValueError("Invalid GUID")
    return "{" + ",".join(f"0x{int(part, 16):08X}u" for part in parts) + "}"


def main():
    graph_bytes = (ROOT / "analysis/pool_dependency_closure.json").read_bytes()
    namespace = json.loads((ROOT / "analysis/namespaced_entities_verified/report.json").read_text())
    if namespace["graph_sha256"] != hashlib.sha256(graph_bytes).hexdigest():
        raise ValueError("Stale private namespace")
    with (ROOT / "analysis/catalog/enemy_targets.tsv").open(encoding="utf-8", newline="") as stream:
        rows = list(csv.DictReader(stream, delimiter="\t"))
    targets = select_roots(json.loads(graph_bytes), namespace, rows)
    by_occurrence = {tuple(target["source"]): target for target in targets}
    with (ROOT / "analysis/catalog/entities.jsonl").open(encoding="utf-8") as stream:
        for line in stream:
            entity = json.loads(line)
            target = by_occurrence.get((entity["archive"], entity["asset"], entity["index"]))
            if target is not None:
                target["components"] = [image.get("class", "") for image in entity["images"]]
    if any("components" not in target for target in targets):
        raise ValueError("Missing root component inventory")
    orientations = {"Wall": 1, "Ceiling": 2, "Floor": 4, "default_FLOOR_descriptor": 4}
    for target in targets:
        mask = 0
        if any(c.endswith("VentComponent") for c in target["components"]):
            for row in rows:
                if (row["class"] == target["family"] and row["multiplayer"] == "False" and
                        row["mode"] == "SPAWNMODE_VENT" and int(row["vent_matches"]) > 0 and
                        not row["inactive_animation"] and not row["active_animation"]):
                    mask |= orientations.get(row["vent_type"], 0)
        target["vent_orientation_mask"] = mask
    lines = ["// Generated by tools/embed_global_targets.py.", "#pragma once", 'namespace ds2 {',
             "struct GlobalTargetRow { Guid guid, source, model; const char* package; const char* family; const char* context; bool ordinary, authored; unsigned ventMask; };",
             "inline constexpr GlobalTargetRow kGlobalTargets[] = {"]
    for row in targets:
        lines.append("    {" + ",".join([words(row["guid"]), words(row["source_guid"]), words(row["model"]),
                     json.dumps(row["package"]), json.dumps(row["family"]), json.dumps(row["context"]),
                     str(row["ordinary"]).lower(), str(row["authored_animation"]).lower(), str(row["vent_orientation_mask"])]) + "},")
    lines += ["};", "}"]
    (ROOT / "src/generated_global_targets.h").write_text("\n".join(lines) + "\n")
    (ROOT / "analysis/global_target_bindings.json").write_text(json.dumps({"runtime_ready": False, "targets": targets}, indent=2))
    print(f"Private enemy roots: {len(targets)}; source occurrences verified")
    print("Roots with DSNPCSpawningComponent:", sum("DSNPCSpawningComponent" in t["components"] for t in targets))


if __name__ == "__main__":
    main()
