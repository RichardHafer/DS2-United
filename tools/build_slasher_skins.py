"""Slasher skins for the Versus slashers of the survival director.

Every Zombie model of the retail game with the character package it lives in
(analysis/catalog/enemy_model_variants.tsv). A pool record carries its source's
model, so this is how the director tells the skin of a donor: the package names
are what DS2Survival.ini [VersusSkins] lists.

Writes src/generated_slasher_skins.h.
"""
import csv
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / "analysis/catalog/enemy_model_variants.tsv"
target = root / "src/generated_slasher_skins.h"


def main():
    rows = []
    with source.open(encoding="utf-8") as f:
        for row in csv.DictReader(f, delimiter="\t"):
            if row["class"] != "Zombie":
                continue
            package = row["package_candidates"].split("|")[0].strip()
            words = row["model_guid"].split("-")
            if not package or len(words) != 4:
                print("skipped (no package):", row["model_assets"])
                continue
            rows.append((tuple(int(w, 16) for w in words), package, row["model_assets"]))
    rows.sort(key=lambda r: r[1])
    if len({r[1] for r in rows}) != len(rows):
        sys.exit("two models share a package")
    lines = [
        "// Generated by tools/build_slasher_skins.py from analysis/catalog/enemy_model_variants.tsv.",
        "// Every retail Zombie model with its character package: the skin names of",
        "// DS2Survival.ini [VersusSkins]. A pool record carries its source's model.",
        "#pragma once",
        "namespace ds2 {",
        "struct SlasherSkinRow { Guid model; const char* package; const char* asset; };",
        "inline constexpr SlasherSkinRow kSlasherSkins[] = {",
    ]
    for model, package, asset in rows:
        guid = ",".join("0x%08Xu" % w for w in model)
        lines.append('    {{%s},"%s","%s"},' % (guid, package, asset))
    lines += ["};", "}  // namespace ds2", ""]
    target.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", target.relative_to(root), len(rows), "skins")


if __name__ == "__main__":
    main()
